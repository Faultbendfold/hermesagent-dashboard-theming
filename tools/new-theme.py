#!/usr/bin/env python3
"""new-theme -- write a commented theme skeleton that already passes theme-check.

    python3 tools/new-theme.py aurora --accent "#7C5CFF"
    python3 tools/new-theme.py aurora --accent "#7C5CFF" --mode dark
    python3 tools/new-theme.py aurora --accent "#7C5CFF" --out themes/

Every colour is derived with the maths the skill documents (canvas near 0.93 in
light mode, ink lifted to >= 7:1 against that canvas, button label >= 3.2), so
the result survives `theme-check.py --strict` and is a real starting point
instead of a placeholder you have to repair first. The generated comments mark
what is dead configuration in the shipped build.
"""

import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "skills", "hermes-dashboard-theming", "scripts"))

import theme_lib as t  # noqa: E402

TEXT_TARGET = 7.0
BUTTON_MIN = 3.2
MUTED_MIN = 4.5


def derive(accent, mode):
    """A complete, contrast-checked colour set for one mode."""
    accent = t.norm_hex(accent)
    if mode == "light":
        canvas = "#F8F9FB"
        ink = t.fit("#111827", canvas, TEXT_TARGET, "#000000")
        card, panel = "#FFFFFF", "#F4F6F9"
        muted_f, border_f, lift = 0.05, 0.14, "#000000"
        primary = t.fit(accent, "#FFFFFF", BUTTON_MIN, "#000000")
    else:
        canvas = "#0F1115"
        ink = t.fit("#E6E8EC", canvas, TEXT_TARGET, "#FFFFFF")
        card, panel = t.mix(canvas, ink, 0.06), t.mix(canvas, ink, 0.035)
        muted_f, border_f, lift = 0.09, 0.20, "#FFFFFF"
        primary = t.fit(accent, canvas, BUTTON_MIN, "#FFFFFF")
    primary_ink = max(("#FFFFFF", canvas), key=lambda c: t.ratio(primary, c))
    muted = t.mix(canvas, ink, muted_f)
    muted_ink = t.fit(t.mix(ink, canvas, 0.45), muted, MUTED_MIN, lift)
    border = t.mix(canvas, ink, border_f)
    success = t.fit("#15803D", card, MUTED_MIN, lift)
    warning = t.fit("#B54708", card, MUTED_MIN, lift)
    destructive = t.fit("#B42318", card, MUTED_MIN, lift)
    return {
        "canvas": canvas, "ink": ink, "card": card, "panel": panel,
        "primary": primary, "primary_ink": primary_ink, "muted": muted,
        "muted_ink": muted_ink, "border": border, "ring": primary,
        "success": success, "warning": warning, "destructive": destructive,
    }


def render(name, label, mode, c):
    rows = [
        ("card", c["card"]), ("cardForeground", c["ink"]),
        ("popover", c["card"]), ("popoverForeground", c["ink"]),
        ("primary", c["primary"]), ("primaryForeground", c["primary_ink"]),
        ("secondary", c["panel"]), ("secondaryForeground", c["ink"]),
        ("muted", c["muted"]), ("mutedForeground", c["muted_ink"]),
        ("accent", c["panel"]), ("accentForeground", c["ink"]),
        ("destructive", c["destructive"]), ("destructiveForeground", c["canvas"] if mode == "dark" else "#FFFFFF"),
        ("success", c["success"]), ("warning", c["warning"]),
        ("border", c["border"]), ("input", c["border"]), ("ring", c["ring"]),
    ]
    lay = []
    a = lay.append
    a("# %s -- generated by tools/new-theme.py, then reviewed by hand." % label)
    a("# Enable with:  hermes config set dashboard.theme %s" % name)
    a("# Check with:   python3 skills/hermes-dashboard-theming/scripts/theme-check.py %s.yaml" % name)
    a("")
    a("name: %s" % name)
    a("label: %s" % label)
    a("description: %s theme in the %s mode." % (label, mode))
    a("")
    a("palette:")
    a("  background: \"%s\"   # the canvas: what everything else is measured against" % c["canvas"])
    a("  midground: \"%s\"    # the ink: lifted to >= 7:1 against the canvas" % c["ink"])
    a("  foreground:")
    a("    hex: \"#FFFFFF\"")
    a("    alpha: 0")
    a("  noiseOpacity: 0")
    a("")
    a("typography:")
    a("  fontSans: '\"Inter\", system-ui, -apple-system, \"Segoe UI\", Roboto, sans-serif'")
    a("  fontMono: 'ui-monospace, \"SF Mono\", Menlo, Consolas, monospace'")
    a("  baseSize: \"15px\"")
    a("  lineHeight: \"1.6\"")
    a("  # fontDisplay is accepted but the shipped build does not use it --")
    a("  # heading fonts need a customCSS rule (references/typography-and-fonts.md).")
    a("")
    a("layout:")
    a("  radius: \"0.8rem\"")
    a("  density: comfortable")
    a("")
    a("colorOverrides:")
    for key, val in rows:
        a("  %s: \"%s\"" % (key, val))
    a("")
    a("# seriesColors is accepted by the server and then dropped: the chart colours")
    a("# only arrive through customCSS (--series-input-token/--series-output-token,")
    a("# each with !important, because the client writes them inline).")
    a("")
    a("componentStyles:")
    a("  card:")
    a("    background: \"%s\"" % c["card"])
    a("  header:")
    a("    background: \"%s\"" % c["panel"])
    a("  sidebar:")
    a("    background: \"%s\"" % c["panel"])
    a("  # Only card/header/sidebar/tab are read at all, and only background,")
    a("  # border-image, clip-path (card additionally box-shadow). badge, page,")
    a("  # progress, backdrop and footer are dead configuration.")
    a("")
    a("customCSS: |")
    a("  /* Everything the tokens cannot reach. Keep this under 32 KiB. */")
    a("  :root {")
    a("    --series-input-token: %s !important;" % c["primary"])
    a("    --series-output-token: %s !important;" % c["ring"])
    a("  }")
    a("")
    return "\n".join(lay) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Write a theme skeleton that already passes theme-check.")
    ap.add_argument("name", help="theme name: lower-case slug, also the file name")
    ap.add_argument("--label", help="display name in the picker (default: from the name)")
    ap.add_argument("--accent", default="#0F766E", help="accent colour as #rrggbb")
    ap.add_argument("--mode", choices=("light", "dark"), default="light")
    ap.add_argument("--out", default=os.path.join(ROOT, "themes"),
                    help="directory to write into (default: themes/)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = ap.parse_args(argv)

    name = args.name.strip()
    if not re.match(r"^[a-z0-9][a-z0-9-]*$", name):
        print("new-theme: name must be a lower-case slug (a-z, 0-9, -)", file=sys.stderr)
        return 2
    if name in t.BUILTIN_THEME_NAMES:
        print("new-theme: %r is a builtin theme name; a user theme cannot shadow it" % name,
              file=sys.stderr)
        return 2
    if not t.is_hex(args.accent):
        print("new-theme: --accent %r is not #rrggbb" % args.accent, file=sys.stderr)
        return 2

    label = args.label or " ".join(w.capitalize() for w in name.split("-"))
    path = os.path.join(args.out, name + ".yaml")
    if os.path.exists(path) and not args.force:
        print("new-theme: %s already exists (use --force to replace it)" % path, file=sys.stderr)
        return 2

    c = derive(args.accent, args.mode)
    text = render(name, label, args.mode, c)
    os.makedirs(args.out, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)

    print("wrote %s (%d bytes)\n" % (path, len(text.encode("utf-8"))))
    print("  pair                   fg        bg          ratio  target")
    for lbl, fg, bg, target in (
        ("body text", c["ink"], c["canvas"], TEXT_TARGET),
        ("text on card", c["ink"], c["card"], 4.5),
        ("button label", c["primary_ink"], c["primary"], BUTTON_MIN),
        ("muted text", c["muted_ink"], c["muted"], MUTED_MIN),
        ("border vs canvas", c["border"], c["canvas"], 1.1),
    ):
        r = t.ratio(fg, bg)
        print("  %-22s %-9s %-11s %5.2f  %s (>= %.1f)"
              % (lbl, fg, bg, r, "ok " if r >= target else "LOW", target))
    print("next:")
    print("  python3 skills/hermes-dashboard-theming/scripts/theme-check.py %s" % path)
    if os.path.abspath(args.out) == os.path.abspath(os.path.join(ROOT, "themes")):
        print("  ./install.sh --activate %s" % name)
    else:
        print('  cp %s "$HERMES_HOME/dashboard-themes/"' % path)
        print("  hermes config set dashboard.theme %s" % name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
