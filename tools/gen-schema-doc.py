#!/usr/bin/env python3
"""gen-schema-doc -- write docs/schema.md from the schema mirror in theme_lib.

The reference table in the documentation is generated from the same constants
`theme-check.py` lints against, so the two cannot drift apart: change
`theme_lib.py`, run this, commit both.

    python3 tools/gen-schema-doc.py            # write docs/schema.md
    python3 tools/gen-schema-doc.py --check    # exit 1 if docs/schema.md is stale
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "skills", "hermes-dashboard-theming", "scripts"))

import theme_lib as t  # noqa: E402

OUT = os.path.join(ROOT, "docs", "schema.md")

PALETTE_LAYERS = (
    ("background", "the canvas", "what every other surface is measured against; nothing else should be guessed if this is missing"),
    ("midground", "the ink", "the default text colour; themes that only set this one still look deliberate"),
    ("foreground", "an overlay", "a tinted layer drawn over the whole page; `alpha: 0` switches it off"),
)

TYPOGRAPHY = (
    ("fontSans", "yes", "the UI font"),
    ("fontMono", "yes", "code blocks and the terminal"),
    ("fontUrl", "yes", "a stylesheet URL, e.g. a Google Fonts link"),
    ("baseSize", "yes", "root font size"),
    ("lineHeight", "yes", "root line height"),
    ("letterSpacing", "yes", "root letter spacing"),
    ("fontDisplay", "no", "stored, but the shipped build never uses it -- headings need customCSS"),
)

LAYOUT = (
    ("radius", "a CSS length", "`1rem`, `12px`"),
    ("density", ", ".join(sorted(t.DENSITIES)), "falls back to comfortable"),
)

ASSETS = ", ".join(sorted(t.NAMED_ASSET_KEYS))


def rows(items):
    """Markdown table body from tuples; the first cell is the key, in code style."""
    out = []
    for item in items:
        cells = ["`%s`" % item[0]] + [str(x) for x in item[1:]]
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def build():
    L = []
    a = L.append
    a("# Theme schema")
    a("")
    a("> Generated by `tools/gen-schema-doc.py` from the schema mirror in")
    a("> `skills/hermes-dashboard-theming/scripts/theme_lib.py`. Do not edit by hand --")
    a("> change the mirror, run the generator, commit both.")
    a("")
    a("Mirror of Hermes **v2026.9.24**: `hermes_cli/web_server_dashboard.py`")
    a("(`_THEME_OVERRIDE_KEYS`, `_THEME_COMPONENT_BUCKETS`, `_THEME_NAMED_ASSET_KEYS`,")
    a("`_THEME_CUSTOM_CSS_MAX`, `_normalise_theme_definition()`) plus what the shipped")
    a("bundle in `hermes_cli/web_dist/assets/` actually reads. The full evidence trail is in")
    a("`skills/hermes-dashboard-theming/references/theme-token-inventory.md`.")
    a("")
    a("A theme is a YAML file in `$HERMES_HOME/dashboard-themes/`. Unknown top-level keys are")
    a("ignored; unknown keys *inside* a known block are dropped without a word, which is why")
    a("`theme-check.py` exists.")
    a("")
    a("## Top-level keys")
    a("")
    a("| Key | Status |")
    a("|---|---|")
    a("| `name` | required -- a theme without it is dropped entirely |")
    a("| `label` | shown in the picker; falls back to the name |")
    a("| `description` | shown under the label in the picker |")
    a("| `palette` | the three layers below |")
    a("| `colorOverrides` | the %d permitted colours below |" % len(t.OVERRIDE_KEYS))
    a("| `typography` | see below |")
    a("| `layout`, `layoutVariant` | see below |")
    a("| `componentStyles` | see below -- mostly dead configuration |")
    a("| `assets` | %s |" % ASSETS)
    a("| `customCSS` | raw CSS, hard cap %d bytes |" % t.CUSTOM_CSS_MAX)
    for key in sorted(t.DROPPED_TOP_LEVEL):
        a("| `%s` | **accepted but never reaches the surface** -- %s |"
          % (key, t.DROPPED_TOP_LEVEL[key]))
    a("")
    a("## `palette`")
    a("")
    a("| Layer | Meaning | Notes |")
    a("|---|---|---|")
    a(rows(PALETTE_LAYERS))
    a("")
    a("Each layer takes either a bare `\"#rrggbb\"` or the `{hex: \"#rrggbb\", alpha: 0.0}` form.")
    a("`palette.warmGlow` and `palette.noiseOpacity` are still accepted for compatibility with")
    a("older themes; both are retro decorations, and `noiseOpacity: 0` switches the grain off.")
    a("")
    a("## `colorOverrides`")
    a("")
    a("Exactly these %d keys are permitted. Anything else is silently discarded." % len(t.OVERRIDE_KEYS))
    a("")
    a("| Key |")
    a("|---|")
    for key in sorted(t.OVERRIDE_KEYS):
        a("| `%s` |" % key)
    a("")
    a("Values must be strings. A bare `#rrggbb` is the only form guaranteed to render")
    a("everywhere; `color-mix()` and `oklab()` values are accepted but only work in a modern")
    a("browser.")
    a("")
    a("## `componentStyles`")
    a("")
    a("The server accepts %d buckets and passes them through as"
      % len(t.COMPONENT_BUCKETS))
    a("`--component-<bucket>-<kebab-prop>`. The shipped build reads only these:")
    a("")
    a("| Bucket | Properties the build reads |")
    a("|---|---|")
    for bucket in sorted(t.COMPONENT_READ):
        a("| `%s` | %s |" % (bucket, ", ".join("`%s`" % p for p in sorted(t.COMPONENT_READ[bucket]))))
    a("")
    dead = sorted(set(t.COMPONENT_BUCKETS) - set(t.COMPONENT_READ))
    a("**Dead configuration** (accepted, emitted as a variable, never read): %s."
      % ", ".join("`%s`" % b for b in dead))
    a("Setting a colour there fakes a change that does not happen.")
    a("")
    a("## `typography`")
    a("")
    a("| Field | Used | What it is |")
    a("|---|---|---|")
    a(rows(TYPOGRAPHY))
    a("")
    a("## `layout`")
    a("")
    a("| Field | Accepted | Notes |")
    a("|---|---|---|")
    a(rows(LAYOUT))
    a("")
    a("`layoutVariant` is one of %s." % ", ".join("`%s`" % v for v in sorted(t.LAYOUT_VARIANTS)))
    a("")
    a("## `customCSS`")
    a("")
    a("Raw CSS in an injected `<style>` tag, capped at %d bytes (%d KiB) and"
      % (t.CUSTOM_CSS_MAX, t.CUSTOM_CSS_MAX // 1024))
    a("deliberately not sanitised -- a theme file has the same trust level as `config.yaml`.")
    a("This is the only lever for everything without a token: speech bubbles, code chips,")
    a("scrollbars, `::selection`, rounded-none surfaces, semantic status colours.")
    a("")
    a("Two things it must handle that the schema cannot:")
    a("")
    a("1. **Chart series colours.** `seriesColors` never arrives. Set")
    a("   `--series-input-token` / `--series-output-token` on `:root` **with `!important`** --")
    a("   the client writes them inline on `<html>`, and inline style wins.")
    a("2. **Semantic colours.** `colorOverrides.success/warning/destructive` are stored but the")
    a("   app hardwires those colours in its stylesheet; a `[class*=\"text-success\"]` rule is")
    a("   what actually repaints the status chips.")
    a("")
    a("## Builtin theme names")
    a("")
    a("A user theme cannot shadow one of these: %s."
      % ", ".join("`%s`" % n for n in sorted(t.BUILTIN_THEME_NAMES)))
    a("")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write docs/schema.md from the schema mirror.")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if docs/schema.md differs from what would be generated")
    args = ap.parse_args(argv)
    text = build()
    on_disk = None
    try:
        with open(OUT, encoding="utf-8") as fh:
            on_disk = fh.read()
    except OSError:
        pass
    if args.check:
        if on_disk != text:
            print("docs/schema.md is stale -- run: python3 tools/gen-schema-doc.py")
            return 1
        print("docs/schema.md is up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (OUT, len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
